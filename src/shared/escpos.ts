export type EscposPaperWidth = 58 | 80
export type EscposCutMode = 'none' | 'partial' | 'full'
export type EscposCodepage = 'cp1252' | 'cp437' | 'cp850' | 'cp858'

export interface EscposLine {
  text: string
  align?: 'left' | 'center' | 'right'
  bold?: boolean
  size?: 'normal' | 'double'
}

export interface EscposOptions {
  codepage?: EscposCodepage
  cutMode?: EscposCutMode
  openDrawer?: boolean
}

