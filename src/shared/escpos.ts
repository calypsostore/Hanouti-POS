export const encodeEscposText = (text: string, codepage: EscposCodepage): Uint8Array => {
  const index = ESCPOS_CODEPAGES[codepage].index
  const bytes = Array.from(text, (character) => {
    const code = character.codePointAt(0) ?? 0
    if (code < 0x80) return code
    if (codepage === 'cp1252') return (code >= 0xa0 && code <= 0xff ? code : CP1252_HIGH[code]) ?? 0x3f
    return CODEPAGE_GLYPHS[index]?.[code] ?? 0x3f
  })
  return new Uint8Array(bytes)
}

export const linesToEscpos = (
  lines: EscposLine[],
  width: EscposPaperWidth,
  options: EscposOptions = {},
): Uint8Array => {
  const codepage = options.codepage ?? 'cp1252'
  const cutMode = options.cutMode ?? 'partial'
  const columns = width === 58 ? 32 : 48
  const output: number[] = []
  const push = (...bytes: number[]) => output.push(...bytes)

  push(0x1b, 0x40)
  push(0x1b, 0x74, ESCPOS_CODEPAGES[codepage].index)
  push(0x1b, 0x61, 0x00)
  for (const line of lines) {
    push(0x1b, 0x61, line.align === 'center' ? 1 : line.align === 'right' ? 2 : 0)
    push(0x1b, 0x45, line.bold ? 1 : 0)
    push(0x1d, 0x21, line.size === 'double' ? 0x11 : 0x00)
    const textColumns = line.size === 'double' ? Math.floor(columns / 2) : columns
    const text = Array.from(line.text).slice(0, textColumns).join('')
    output.push(...encodeEscposText(`${text}\n`, codepage))
  }
  push(0x1d, 0x21, 0x00, 0x1b, 0x45, 0x00, 0x1b, 0x64, 0x04)
  if (options.openDrawer) push(0x1b, 0x70, 0x00, 0x3c, 0x78)
  if (cutMode === 'partial') push(0x1d, 0x56, 0x01)
  if (cutMode === 'full') push(0x1d, 0x56, 0x00)
  return new Uint8Array(output)
}
